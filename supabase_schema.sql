-- 1. TABEL REFLEKSI DIRI SISWA
CREATE TABLE IF NOT EXISTS public.refleksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    "userId" TEXT NOT NULL,
    "userClass" TEXT NOT NULL,
    q1 TEXT,
    q2 TEXT
);

-- 2. TABEL SKOR & JAWABAN EVALUASI
CREATE TABLE IF NOT EXISTS public.evaluasi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    "userId" TEXT NOT NULL,
    "userClass" TEXT NOT NULL,
    skor INTEGER DEFAULT 0,
    jawaban JSONB
);

-- 3. TABEL KEGIATAN KONSELING KELOMPOK (RPL 1, RPL 2, RPL 3)
CREATE TABLE IF NOT EXISTS public.konseling_rpl (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    "userId" TEXT NOT NULL,
    "userClass" TEXT NOT NULL,
    rpl TEXT NOT NULL,
    kelebihan TEXT,
    kelemahan TEXT,
    pemicu TEXT,
    komitmen TEXT
);

-- ==============================================================================
-- KEAMANAN DATA: ROW LEVEL SECURITY (RLS) & POLICIES
-- Memberikan akses penuh bagi aplikasi (anon) untuk membaca, menambah, dan menghapus
-- ==============================================================================

ALTER TABLE public.refleksi ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evaluasi ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.konseling_rpl ENABLE ROW LEVEL SECURITY;

-- Policy untuk tabel refleksi
DROP POLICY IF EXISTS "Izinkan akses publik refleksi" ON public.refleksi;
CREATE POLICY "Izinkan akses publik refleksi" ON public.refleksi
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Policy untuk tabel evaluasi
DROP POLICY IF EXISTS "Izinkan akses publik evaluasi" ON public.evaluasi;
CREATE POLICY "Izinkan akses publik evaluasi" ON public.evaluasi
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Policy untuk tabel konseling_rpl
DROP POLICY IF EXISTS "Izinkan akses publik konseling_rpl" ON public.konseling_rpl;
CREATE POLICY "Izinkan akses publik konseling_rpl" ON public.konseling_rpl
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- ==============================================================================
-- INDEX PERFORMA TINGGI (UNTUK MENANGANI BANYAK DATA SISWA DENGAN CEPAT)
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_refleksi_user ON public.refleksi ("userId", "userClass");
CREATE INDEX IF NOT EXISTS idx_evaluasi_user ON public.evaluasi ("userId", "userClass");
CREATE INDEX IF NOT EXISTS idx_konseling_rpl_user ON public.konseling_rpl ("userId", "userClass", rpl);
CREATE INDEX IF NOT EXISTS idx_refleksi_created_at ON public.refleksi (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_evaluasi_created_at ON public.evaluasi (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_konseling_rpl_created_at ON public.konseling_rpl (created_at DESC);

